// Build tool: turns every file under a directory into a C++ source file with the contents as byte arrays.
//   rangka_embed <templates-dir> <output.cpp>
// Byte arrays rather than string literals, because MSVC limits string literals to 64 KB.
// Carriage returns are dropped, so a Windows checkout with CRLF line endings embeds the same bytes as Linux.

#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <vector>

namespace fs = std::filesystem;

int main(int argc, char** argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: rangka_embed <templates-dir> <output.cpp>\n");
        return 2;
    }
    fs::path root = argv[1];
    std::vector<fs::path> files;
    for (auto& entry : fs::recursive_directory_iterator(root)) {
        if (entry.is_regular_file()) files.push_back(entry.path());
    }
    // sorted, so the output (and the order files are generated in) is the same on every machine
    std::sort(files.begin(), files.end(), [&](const fs::path& a, const fs::path& b) {
        return fs::relative(a, root).generic_string() < fs::relative(b, root).generic_string();
    });

    std::ostringstream out;
    out << "// Generated by tools/embed.cpp from templates/. Do not edit.\n"
           "#include \"core/embedded.hpp\"\n\nnamespace rangka {\nnamespace {\n\n";
    size_t total = 0;
    for (size_t i = 0; i < files.size(); ++i) {
        std::ifstream in(files[i], std::ios::binary);
        std::string data((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        data.erase(std::remove(data.begin(), data.end(), '\r'), data.end());
        total += data.size();
        out << "constexpr char f" << i << "[] = {";
        for (size_t j = 0; j < data.size(); ++j) {
            if (j % 24 == 0) out << "\n";
            out << static_cast<int>(static_cast<signed char>(data[j])) << ",";
        }
        out << "0};\n";
    }
    out << "\nconstexpr EmbeddedFile kFiles[] = {\n";
    for (size_t i = 0; i < files.size(); ++i) {
        out << "    {\"" << fs::relative(files[i], root).generic_string() << "\", {f" << i << ", sizeof(f" << i
            << ") - 1}},\n";
    }
    if (files.empty()) out << "    {\"\", {}},\n";
    out << "};\n\n}  // namespace\n\nstd::span<const EmbeddedFile> embedded_templates() {\n"
           "    return {kFiles, "
        << files.size() << "};\n}\n\n}  // namespace rangka\n";

    std::string text = out.str();
    // only rewrite when something changed, so builds stay incremental
    std::ifstream existing(argv[2], std::ios::binary);
    std::string old((std::istreambuf_iterator<char>(existing)), std::istreambuf_iterator<char>());
    if (old != text) {
        std::ofstream(argv[2], std::ios::binary) << text;
    }
    std::printf("embedded %zu templates (%zu bytes)\n", files.size(), total);
    return 0;
}
